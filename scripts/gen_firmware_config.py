"""Generate firmware/emg_giga/config_gen.h from config/config.toml.

    python -m scripts.gen_firmware_config               # refuses while needed pins are TODO_HW
    python -m scripts.gen_firmware_config --allow-todo  # placeholders (-1), for compile checks only

With placeholders the firmware compiles, answers INFO with "pins_configured": false and refuses
to START, so it never drives pins that are not known.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from common.config import REPO_ROOT, TODO_HW, Config, load_config

OUT_PATH = REPO_ROOT / "firmware" / "emg_giga" / "config_gen.h"
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _pin(value, key: str, allow_todo: bool, missing: list[str]) -> str:
    if value == TODO_HW:
        missing.append(key)
        return "-1"
    if isinstance(value, int) or (isinstance(value, str) and _IDENT.match(value)):
        return str(value)
    raise ValueError(f"{key}: pin must be an integer or a pin name like D10/A0, got {value!r}")


def render(cfg: Config, allow_todo: bool) -> tuple[str, list[str]]:
    source = cfg["emg.source"]
    if source not in ("ads1299_spi", "giga_adc"):
        raise ValueError(f"emg.source must be ads1299_spi or giga_adc, got {source!r}")
    n_ch = int(cfg["emg.n_channels"])
    if not 1 <= n_ch <= 8:
        raise ValueError("emg.n_channels must be 1..8")
    missing: list[str] = []
    L = [
        "// Generated by scripts/gen_firmware_config.py from config/config.toml. Do not edit.",
        "#pragma once",
        "",
        f'#define CONFIG_SHA256 "{cfg.sha256}"',
        f"#define EMG_SOURCE_ADS1299 {int(source == 'ads1299_spi')}",
        f"#define EMG_SOURCE_GIGA_ADC {int(source == 'giga_adc')}",
        f"#define EMG_N_CHANNELS {n_ch}",
        f"#define EMG_FS_HZ {int(cfg['emg.fs_hz'])}",
        "",
        f"#define ADS_GAIN {int(cfg['emg.ads1299.gain'])}",
        f"#define ADS_VREF_V {float(cfg['emg.ads1299.vref_v'])}f",
        f"#define ADS_SPI_HZ {int(cfg['emg.ads1299.spi_clock_hz'])}",
    ]
    for name in ("cs", "drdy", "reset", "start", "pwdn"):
        key = f"emg.ads1299.pin_{name}"
        value = _pin(cfg[key], key, allow_todo, missing if source == "ads1299_spi" else [])
        L.append(f"#define ADS_PIN_{name.upper()} {value}")

    pins = cfg["emg.giga_adc.pins"][:n_ch]
    if source == "giga_adc" and len(pins) < n_ch:
        raise ValueError("emg.giga_adc.pins has fewer pins than emg.n_channels")
    gain = cfg["emg.giga_adc.front_end_gain"]
    if gain == TODO_HW:
        if source == "giga_adc":
            missing.append("emg.giga_adc.front_end_gain")
        gain = 1.0
    L += [
        "",
        f"#define GIGA_ADC_PINS {', '.join(_pin(p, 'emg.giga_adc.pins', allow_todo, missing) for p in pins)}",
        f"#define GIGA_ADC_VREF_V {float(cfg['emg.giga_adc.vref_v'])}f",
        f"#define GIGA_ADC_FRONT_END_GAIN {float(gain)}f",
        "",
        f"#define SYNC_LED_PIN {_pin(cfg['sync.led_pin'], 'sync.led_pin', allow_todo, missing)}",
        f"#define SYNC_LED_ACTIVE_HIGH {int(bool(cfg['sync.led_active_high']))}",
        f"#define SYNC_FLASH_MS {int(cfg['sync.flash_ms'])}",
        f"#define CAL_BUTTON_PIN {_pin(cfg['calibration.button_pin'], 'calibration.button_pin', allow_todo, missing)}",
        f"#define CAL_BUTTON_ACTIVE_LOW {int(bool(cfg['calibration.button_active_low']))}",
        "",
    ]
    # The calibration button is only needed in INFER mode; it does not block RECORD.
    blocking = [k for k in missing if k != "calibration.button_pin"]
    L.append(f"#define HW_PINS_CONFIGURED {int(not blocking)}")
    if blocking:
        L.append(f'#warning "TODO_HW placeholders: {", ".join(blocking)}. The firmware will refuse to START."')
    return "\n".join(L) + "\n", blocking


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--allow-todo", action="store_true", help="emit -1 placeholders for TODO_HW pins")
    ap.add_argument("--out", type=Path, default=OUT_PATH)
    args = ap.parse_args()
    cfg = load_config()
    text, missing = render(cfg, args.allow_todo)
    if missing and not args.allow_todo:
        sys.exit("TODO_HW values needed by the firmware: " + ", ".join(missing)
                 + "\nset them in config/config.toml, or use --allow-todo for a compile check")
    args.out.write_text(text, encoding="utf-8")
    print(f"written {args.out}" + (f" (placeholders for {', '.join(missing)})" if missing else ""))


if __name__ == "__main__":
    main()
